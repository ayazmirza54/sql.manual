export function px(name, cls = '') {
  const rows = ICONS[name];
  if (!rows) throw new Error(`pixel icon not found: ${name}`);
  let rects = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== '#') continue;
      let w = 1;
      while (row[x + w] === '#') w++;
      rects += `<rect x="${x}" y="${y}" width="${w}" height="1"/>`;
      x += w - 1;
    }
  });
  return `<svg class="pxi${cls ? ' ' + cls : ''}" viewBox="0 0 12 12" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${rects}</svg>`;
}
